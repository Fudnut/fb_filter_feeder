// Builds fb-feed-filter.user.js from the extension source.
// Usage: node userscript/build.mjs   (run from the feed-bouncer folder)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..");
const out = join(repo, "..", "fb-feed-filter.user.js");
const read = (path) => readFileSync(join(repo, path), "utf8").replace(/^﻿/, "");

const manifest = JSON.parse(read("manifest.json"));
const version = manifest.version;

const header = `// ==UserScript==
// @name         FB Feed Filter
// @namespace    https://github.com/Fudnut/feed-bouncer
// @version      ${version}
// @description  ${manifest.description}
// @author       ${manifest.author}
// @match        https://facebook.com/*
// @match        https://*.facebook.com/*
// @run-at       document-start
// @inject-into  content
// @noframes
// @grant        GM.getValue
// @grant        GM.setValue
// @grant        GM.addStyle
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_addStyle
// @grant        GM_registerMenuCommand
// @grant        GM_addValueChangeListener
// ==/UserScript==
// Generated by userscript/build.mjs from feed-bouncer ${version}. Do not edit by hand.
`;

const body = [
  `const FFFC_VERSION = ${JSON.stringify(version)};`,
  read("userscript/shim.js"),
  `fffcGM.addStyle(${JSON.stringify(read("content.css"))});`,
  read("core.js"),
  read("content.js"),
  read("userscript/panel.js")
].join("\n\n");

writeFileSync(out, `${header}\n(function fbFeedFilterUserscript() {\n"use strict";\n\n${body}\n})();\n`);
console.log(`Wrote ${out} (${version})`);
